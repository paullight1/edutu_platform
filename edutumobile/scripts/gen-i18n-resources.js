#!/usr/bin/env node
/**
 * Regenerates lib/i18n/resources.ts from the JSON catalogs in
 * lib/i18n/locales/<lang>/<namespace>.json. Metro cannot require() dynamic
 * paths, so every catalog must be statically imported — run this after
 * adding a language or a namespace:
 *
 *   node scripts/gen-i18n-resources.js
 */
const fs = require('fs');
const path = require('path');

const localesDir = path.join(__dirname, '..', 'lib', 'i18n', 'locales');
const outFile = path.join(__dirname, '..', 'lib', 'i18n', 'resources.ts');

const langs = fs
    .readdirSync(localesDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();

const imports = [];
const resourceEntries = [];

for (const lang of langs) {
    const files = fs
        .readdirSync(path.join(localesDir, lang))
        .filter((file) => file.endsWith('.json'))
        .sort();
    const nsEntries = [];
    for (const file of files) {
        const ns = path.basename(file, '.json');
        const varName = `${lang}_${ns}`;
        imports.push(`import ${varName} from './locales/${lang}/${file}';`);
        nsEntries.push(`        ${ns}: ${varName},`);
    }
    resourceEntries.push(`    ${lang}: {\n${nsEntries.join('\n')}\n    },`);
}

const content = `// AUTO-GENERATED by scripts/gen-i18n-resources.js — do not edit by hand.
// Run \`node scripts/gen-i18n-resources.js\` after adding a language or namespace.
${imports.join('\n')}

export const resources = {
${resourceEntries.join('\n')}
} as const;

export const namespaces = Object.keys(resources.en);
`;

fs.writeFileSync(outFile, content);
console.log(`Wrote ${outFile} (${langs.length} languages: ${langs.join(', ')})`);
